package dev.antcraft;

import com.mojang.serialization.Codec;
import java.util.ArrayDeque;
import java.util.Deque;
import java.util.HashSet;
import java.util.Set;
import net.fabricmc.fabric.api.attachment.v1.AttachmentRegistry;
import net.fabricmc.fabric.api.attachment.v1.AttachmentType;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerChunkEvents;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerLifecycleEvents;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents;
import net.minecraft.resources.Identifier;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.util.datafix.DataFixTypes;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.chunk.LevelChunk;
import net.minecraft.world.level.saveddata.SavedData;
import net.minecraft.world.level.saveddata.SavedDataType;

/**
 * Brings existing AntCraft worlds up to date when the mod gets new features.
 *
 * <p><b>Chunks</b> carry an AntCraft version (a Fabric data attachment, saved with the chunk).
 * Freshly generated chunks get {@link #CHUNK_VERSION}. A chunk generated by an older AntCraft (no
 * or a lower version) is queued when it loads, and the missing upgrade steps run on it a few chunks
 * per tick. Every step only adds things to open air or wakes fluids, so player builds and mined
 * tunnels are left alone.
 *
 * <p><b>The world</b> carries a version too ({@code data/antcraft_world_version.dat}), for upgrades
 * that are not per chunk; they run once on server start.
 *
 * <p>Adding a feature later: bump {@link #CHUNK_VERSION} (or {@link #WORLD_VERSION}) and add a
 * {@code case} to {@link #upgradeChunk} (or {@link #upgradeWorld}).
 */
public final class WorldUpgrade {
	private WorldUpgrade() {}

	/**
	 * Chunk versions:
	 * <ol>
	 *   <li>denser forest light grid (saplings and crops grow everywhere), wall vines, generated
	 *       lava and water flow</li>
	 * </ol>
	 */
	public static final int CHUNK_VERSION = 1;
	/** World versions: 1 = first versioned release (nothing to migrate yet). */
	public static final int WORLD_VERSION = 1;

	private static final int CHUNKS_PER_TICK = 2;

	public static final AttachmentType<Integer> CHUNK_VERSION_ATTACHMENT = AttachmentRegistry.<Integer>builder()
		.persistent(Codec.INT)
		.buildAndRegister(Identifier.fromNamespaceAndPath(AntCraft.MOD_ID, "chunk_version"));

	private static final Deque<ChunkPos> QUEUE = new ArrayDeque<>();
	private static final Set<ChunkPos> QUEUED = new HashSet<>();
	private static int upgraded;

	public static void register() {
		ServerChunkEvents.CHUNK_LOAD.register(WorldUpgrade::onChunkLoad);
		ServerTickEvents.END_SERVER_TICK.register(WorldUpgrade::tick);
		ServerLifecycleEvents.SERVER_STARTED.register(WorldUpgrade::upgradeWorld);
		ServerLifecycleEvents.SERVER_STOPPED.register(server -> {
			QUEUE.clear();
			QUEUED.clear();
			upgraded = 0;
		});
	}

	private static void onChunkLoad(ServerLevel level, LevelChunk chunk, boolean generated) {
		if (level != level.getServer().overworld() || !(level.getChunkSource().getGenerator() instanceof StripChunkGenerator strip)) return;
		if (generated) {
			chunk.setAttached(CHUNK_VERSION_ATTACHMENT, CHUNK_VERSION);
			return;
		}
		if (!strip.bounds().chunkOverlaps(chunk.getPos())) return;
		if (chunk.getAttachedOrElse(CHUNK_VERSION_ATTACHMENT, 0) >= CHUNK_VERSION) return;
		if (QUEUED.add(chunk.getPos())) QUEUE.add(chunk.getPos());
	}

	private static void tick(MinecraftServer server) {
		if (QUEUE.isEmpty()) return;
		ServerLevel level = server.overworld();
		if (!(level.getChunkSource().getGenerator() instanceof StripChunkGenerator strip)) {
			QUEUE.clear();
			QUEUED.clear();
			return;
		}
		for (int i = 0; i < CHUNKS_PER_TICK && !QUEUE.isEmpty(); i++) {
			ChunkPos pos = QUEUE.poll();
			LevelChunk chunk = level.getChunkSource().getChunkNow(pos.x(), pos.z());
			if (chunk == null) {
				QUEUED.remove(pos); // unloaded again: re-queued when it next loads
				continue;
			}
			// steps also write into the neighbouring chunks (vines, lights across the border): wait
			// until all of them are loaded (chunks at the edge of the view distance)
			if (!neighboursLoaded(level, pos)) {
				QUEUE.add(pos);
				continue;
			}
			QUEUED.remove(pos);
			int from = chunk.getAttachedOrElse(CHUNK_VERSION_ATTACHMENT, 0);
			for (int version = from + 1; version <= CHUNK_VERSION; version++) upgradeChunk(level, strip, chunk, version);
			chunk.setAttached(CHUNK_VERSION_ATTACHMENT, CHUNK_VERSION);
			chunk.markUnsaved();
			upgraded++;
			if (QUEUE.isEmpty()) AntCraft.LOGGER.info("AntCraft: upgraded {} chunks to version {}", upgraded, CHUNK_VERSION);
		}
	}

	private static boolean neighboursLoaded(ServerLevel level, ChunkPos pos) {
		for (int dx = -1; dx <= 1; dx++) {
			for (int dz = -1; dz <= 1; dz++) {
				if (level.getChunkSource().getChunkNow(pos.x() + dx, pos.z() + dz) == null) return false;
			}
		}
		return true;
	}

	private static void upgradeChunk(ServerLevel level, StripChunkGenerator strip, LevelChunk chunk, int version) {
		switch (version) {
			case 1 -> strip.retrofitForests(level, chunk);
			default -> {}
		}
	}

	// ------------------------------------------------------------------ world

	private static final class Data extends SavedData {
		static final Codec<Data> CODEC = Codec.INT.fieldOf("version").xmap(Data::new, data -> data.version).codec();
		static final SavedDataType<Data> TYPE = new SavedDataType<>(
			Identifier.fromNamespaceAndPath(AntCraft.MOD_ID, "world_version"), Data::new, CODEC, DataFixTypes.SAVED_DATA_COMMAND_STORAGE
		);

		int version;

		Data() {
			this(0);
		}

		Data(int version) {
			this.version = version;
		}
	}

	private static void upgradeWorld(MinecraftServer server) {
		ServerLevel overworld = server.overworld();
		if (!AntCraft.isStripLevel(overworld)) return;
		Data data = overworld.getDataStorage().computeIfAbsent(Data.TYPE);
		if (data.version >= WORLD_VERSION) return;
		int from = data.version;
		for (int version = from + 1; version <= WORLD_VERSION; version++) {
			switch (version) {
				default -> {}
			}
		}
		data.version = WORLD_VERSION;
		data.setDirty();
		AntCraft.LOGGER.info("AntCraft: world upgraded from version {} to {}", from, WORLD_VERSION);
	}
}
